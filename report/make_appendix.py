"""Copy every field plot of the final study into report/figs/runs and write
report/appendix_fields.tex (one subsection per run).

    .venv/bin/python report/make_appendix.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
HERE = Path(__file__).resolve().parent
OUT = HERE / "figs" / "runs"
OUT.mkdir(parents=True, exist_ok=True)

# (run folder, file prefix in fields/, title, BO/grid progress plot?)
ENTRIES = [
    ("One outlet, 2D", None, None, False),
    ("final_u2d_straight_ref_single", "design", "2D straight reference, fully heated (heater on the whole 24\\mm)", False),
    ("final_u2d_straight_ref", "run0001", "2D straight reference, best heater window (start 0, length 10\\,\\%): 388\\mK", False),
    ("final_u2d_sine", "run0050", "2D sine, BO best \\#50 ($\\lambda$ 11.14, $a$ 1, heater 30\\,\\%): 120\\mK", True),
    ("final_u2d_sine_grid", "run0112", "2D sine, grid best \\#112 ($\\lambda$ 11.10, $a$ 1, heater 30\\,\\%): 120\\mK", True),
    ("final_u2d_serp", "run0051", "2D serpentine, BO best \\#51 ($\\lambda$ 8.72, $A$ 3.10, heater 60\\,\\%): 11.9\\mK", True),
    ("final_u2d_serp_grid", "run0108", "2D serpentine, grid best \\#108 ($\\lambda$ 8.34, $A$ 2.13, heater 40\\,\\%): 6.3\\mK", True),
    ("One outlet, 3D (depth 3\\,mm)", None, None, False),
    ("final_u3d_straight_ref_single", "design", "3D straight reference, fully heated (heater on all four walls, 24\\mm)", False),
    ("final_u3d_straight_ref", "run0001", "3D straight reference, best heater window (1.2\\mm{} at the start): 378\\mK", False),
    ("final_u3d_serp", "run0029", "3D serpentine, BO best \\#29 ($\\lambda$ 7.26, $A$ 3.5, heater 19.2\\mm): 27.4\\mK", True),
    ("Four branches, 2D", None, None, False),
    ("final_b2d_straight_ref", "run0001", "Branched straight reference, analytic openings $\\rho$ 0.532, fully heated: spread 970\\mK, flow 0.87\\,\\%", False),
    ("final_b2d_straight", "run0016", "Branched straight, BO best \\#16 ($\\rho$ 0.540, heater 2.4\\mm, clamped at 99\\,$^\\circ$C): 515\\mK, 0.16\\,\\%", True),
    ("final_b2d_sine", "run0150", "Branched sine + straight, BO best \\#150: 116\\mK, 0.82\\,\\%", True),
    ("final_b2d_serp", "run0150", "Branched serpentine + straight, BO best \\#150: 12.3\\mK, 3.9\\,\\%", True),
]
KINDS = [("maps", "Temperature rise, temperature gradient and speed (mid-depth plane in 3D). Red: heated wall. "
                  "The title's ``outlet RMS'' is the area-weighted $\\ell_{2,\\mathrm{area}}$.", 0.95),
         ("presplit", "Cross-section just before the split, cut into the four branch inlets, next to each branch outlet.", 0.95),
         ("outlet", "Outlet temperature (and, in 3D, the outlet plane).", 0.75),
         ("slices", "Temperature profiles across the channel at several $x$ stations.", 0.62),
         ("slices_u", "Velocity on cross-sections (3D).", 0.85),
         ("profile", "Speed and temperature across the channel at several $x$ stations, and the full score table of the design.", 0.8),
         ("along_x", "Bulk, mean, min and max temperature along the channel.", 0.8)]

lines = ["% generated by make_appendix.py", "\\section{Field plots of every run}\\label{app:fields}",
         "Every plot below is from the fine mesh. Unless noted, the design shown uses the best heater window "
         "found by the sweep. Files: \\texttt{runs/<run>/fields/}."]
n = 0
for run, prefix, title, prog in ENTRIES:
    if prefix is None:
        lines.append(f"\\subsection{{{run}}}")
        continue
    lines += ["\\clearpage", f"\\subsubsection*{{{title}}}",
              f"\\noindent\\texttt{{runs/{run.replace('_', chr(92) + '_')}}}\\par\\medskip"]
    for kind, cap, wd in KINDS:
        src = RUNS / run / "fields" / f"{prefix}_fine_{kind}.png"
        if not src.exists():
            continue
        dst = OUT / f"{run}_{kind}.png"
        shutil.copy2(src, dst)
        n += 1
        lines += ["\\begin{figure}[H]\\centering",
                  f"\\includegraphics[width={wd}\\textwidth,height=0.8\\textheight,keepaspectratio]{{runs/{dst.name}}}",
                  f"\\caption{{{cap}}}", "\\end{figure}"]
    if prog:
        for kind in ("progress_loss",):
            src = RUNS / run / "report" / f"{kind}.png"
            if src.exists():
                dst = OUT / f"{run}_{kind}.png"
                shutil.copy2(src, dst)
                n += 1
                lines += ["\\begin{figure}[H]\\centering",
                          f"\\includegraphics[width=0.85\\textwidth]{{runs/{dst.name}}}",
                          "\\caption{Search history: loss of every evaluation, best so far, and the parameters.}",
                          "\\end{figure}"]
(HERE / "appendix_fields.tex").write_text("\n".join(lines) + "\n")
print(f"{n} figures copied, appendix written")
