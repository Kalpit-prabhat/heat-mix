"""Writes the case YAMLs of the final study (cases/final/*.yaml).  Common settings:
w 3 mm, heated/wavy channel 24 mm, depth 3 mm, 6 mL/min, T_in 70 C, dT 2 K,
heater <= 99 C, h_loss 2 W/m2K.  One outlet: 2 mm inlet port, 3 mm straight before
the exit plane.  Four branches: fan 6 mm, outlet ports 2 mm at 4 mm pitch, h_loss_br 10.

    .venv/bin/python cases/final/make_cases.py
"""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
# COMSOL install: set the environment variable COMSOL_ROOT to the COMSOL folder that
# holds bin/ and mli/ (e.g. .../comsol64/multiphysics) before running
COMSOL = {"port": 2070, "start_server": True,
          "comsol_cmd": "${COMSOL_ROOT}/bin/comsol",
          "mli_path": "${COMSOL_ROOT}/mli",
          "server_args": ["-np", "4"], "timeout_s": 1800, "reuse_model": True}
WATER = {"rho0": (972.4, "kg/m^3"), "mu0": (0.355e-3, "Pa*s"), "k0": (0.669, "W/(m*K)"),
         "Cp0": (4196, "J/(kg*K)")}
COMMON = {"w": (3, "mm"), "depth": (3, "mm"), "Qv": (6, "ml/min"), "T_in": (343.15, "K"),
          "dT_target": (2, "K"), "T_heat_max": (372.15, "K"), "h_heat": (1e5, "W/(m^2*K)"),
          "h_loss": (2, "W/(m^2*K)"), "T_amb": (293.15, "K"), **WATER}
HEAT_L = [round(0.1 * i, 2) for i in range(1, 11)]              # heater-1 length sweep (fractions)
HEAT_SL = [[round(s, 3), round(l, 3)] for s in [0.05 * i for i in range(19)]
           for l in [0.05 * j for j in range(1, 21)] if s + l <= 1.0 + 1e-9]   # start x length
# sine amplitude as a fraction of the bend-radius limit (walls must not fold)
A_SINE = "a*min(3.5[mm], lam^2/(4*pi^2*(w/2 + 0.05[mm])))"
R_SERP = (1.55, "mm")                                            # w/2 + 0.05 mm


def fx(d):
    return {k: ({"value": v[0], "unit": v[1]} if isinstance(v, tuple) else {"value": v, "unit": ""})
            for k, v in d.items()}


def write(name, desc, case, variables, fixed, loss, mesh, opt, extra_opts=None, constraints=None,
          grid=None, nw=6, port=2070):
    c = {"case": case, "variables": variables, "constraints": constraints or [], "fixed": fx(fixed),
         "loss": loss, "comsol_opts": {**(extra_opts or {}), "mesh": mesh},
         "optimizer": {"seed": 0, "fine_top_min_sep": 0.1, "n_workers": nw, "xi": 0.01,
                       "n_candidates": 20000, "failure_penalty": 0.5, **opt},
         "comsol": {**COMSOL, "port": port},
         "output": {"name": f"final_{name}", "save_mph_coarse": False, "save_mph_fine": False,
                    "fields_best": True, "progress_every": 5}}
    if grid:
        c["grid"] = grid
    if not c["constraints"]:
        del c["constraints"]
    txt = f"# Final study: {desc}\n# generated by cases/final/make_cases.py - edit that file, not this one\n"
    (HERE / f"{name}.yaml").write_text(txt + yaml.safe_dump(c, sort_keys=False, width=110))


# ---------------------------------------------------------------- 2D, one outlet
SPLIT = {"function": "sine_split_2d", "matlab_dir": "../sine_split_2d"}
U2D = {**COMMON, "L_port": (2, "mm"), "L_main": (26.5, "mm"), "f_sine": 24 / 26.5,   # wavy 24 + straight 2.5
       "L_fan": (0.25, "mm"), "L_out": (0.25, "mm"), "L_ext": (3, "mm"),            # exit 3 mm after the waves
       "n_br": 1, "p_out": (4, "mm"), "phi": 0, "heat1_s": 0, "heat2_s": 0, "heat2_l": 0,
       "dT_h2": (0, "K"), "h_loss_br": (2, "W/(m^2*K)"), "dxs": (0.1, "mm"), "R_bend": R_SERP}
M2 = {"coarse": {"type": "mapped", "n_b": 24, "w_ratio": 3, "hmax": 0.07},
      "fine": {"type": "mapped", "n_b": 48, "w_ratio": 3, "hmax": 0.035}}
L_FLOW = {"primary": "l2_flow", "sweep_best": True}
O_2D = {"ny": 80, "flow_ramp": "0.1 0.4 1", "profile_nb": 60}

write("u2d_straight_ref", "2D straight 3 mm channel, fully heated (reference; heater sweep of start x "
      "length on the same flow gives the heater optimum)", SPLIT,
      {"lam": {"min": 5, "max": 6, "unit": "mm"}},                 # dummy (A = 0)
      {**U2D, "A": (0, "mm"), "wall_mode": 0, "heat1_l": 1}, L_FLOW, M2,
      {"n_init": 1, "n_coarse": 1, "fine_top_k": 1}, {**O_2D, "heat_list": HEAT_SL}, nw=1, port=2070)
write("u2d_sine", "2D sine (constant width), lam, a = A/A_max(lam); heater from the channel start, "
      "length by heater sweep", SPLIT,
      {"lam": {"min": 1.5, "max": 20, "unit": "mm", "log": True}, "a": {"min": 0.0, "max": 1.0, "unit": ""}},
      {**U2D, "A": A_SINE, "wall_mode": 0, "heat1_l": 1}, L_FLOW, M2,
      {"n_init": 12, "n_coarse": 50, "fine_top_k": 3}, {**O_2D, "heat_list": [[0, x] for x in HEAT_L]},
      grid={"L0": {"lam": 12, "a": 8}, "zoom": [[3, 0.5], [1, 0.25]], "fine_top": 3}, nw=3, port=2070)
write("u2d_serp", "2D serpentine (R_bend 1.55 mm), lam, A <= 3.5 mm; heater from the channel start, "
      "length by heater sweep", SPLIT,
      {"lam": {"min": 6.5, "max": 20, "unit": "mm", "log": True}, "A": {"min": 0.0, "max": 3.5, "unit": "mm"}},
      {**U2D, "wall_mode": 1, "heat1_l": 1}, L_FLOW, M2,
      {"n_init": 12, "n_coarse": 50, "fine_top_k": 3}, {**O_2D, "heat_list": [[0, x] for x in HEAT_L]},
      grid={"L0": {"lam": 10, "A": 8}, "zoom": [[3, 0.5], [1, 0.25]], "fine_top": 3}, nw=3, port=2080)

